-- ── 1. Одна реорганизация импортом на тенант за раз ─────────────────────────────────────
-- Применение идёт фоновой задачей `org.import_apply` (`32` §11). Второй запуск, пока первый в
-- очереди или применяется, сервис отклоняет `409 import_in_progress`; индекс держит то же
-- правило в БД — две гонящиеся кнопки «Запустити» не поставят в очередь два импорта сразу.
-- Задание, зависшее дольше получаса (упал воркер), сервис закрывает `failed` перед проверкой.
CREATE UNIQUE INDEX "uq_import_jobs_org_structure_active" ON "import_jobs" USING btree ("tenant_id")
  WHERE "kind" = 'org_structure' AND "status" IN ('queued', 'applying');--> statement-breakpoint

-- ── 2. Конфликты одного импорта ─────────────────────────────────────────────────────────
-- Итог импорта ведёт на «Протокол конфліктів» его строк: петли и висячие узлы, которые не
-- попали в дерево (условие выхода PR-31). Полный индекс по `tenant_id` у таблицы уже есть
-- (0033), этот — частичный рядом с ним, только для строк импорта.
CREATE INDEX "idx_org_conflicts_import_job" ON "org_conflicts" USING btree ("tenant_id", "import_job_id")
  WHERE "import_job_id" IS NOT NULL;
