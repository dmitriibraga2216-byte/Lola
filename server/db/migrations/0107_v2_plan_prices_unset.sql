-- Написана руками: снимок drizzle не пересобирается начиная с `0056` (см. `0098`). Схема не меняется.
--
-- Цены платформы в код не зашиваются — их задаёт оператор в каталоге тарифов консоли. `0009` засеял
-- «Точку» и «Мережу» ценами-заглушками 1500 и 6000 ₴, которых никто не утверждал; они снимаются в
-- `null` — «ціну не задано», консоль показывает это оператору. Только если цена всё ещё та самая
-- заглушка: цену, которую оператор уже поменял, миграция не трогает. «Пробний» остаётся `0` —
-- бесплатность пробного периода — суть тарифа, а не цена. `plan_prices` `0009`…`0105` не засевали.
UPDATE "plans" SET "price_uah" = NULL
 WHERE ("code" = 'point' AND "price_uah" = 1500)
    OR ("code" = 'network' AND "price_uah" = 6000);
