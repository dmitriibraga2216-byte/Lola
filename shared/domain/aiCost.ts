/**
 * Стоимость вызова модели (`docs/v2/30-ai-interview.md` §3.2 `ai_calls.cost_minor`, §9.5; `44`
 * Р-AI2.3). Цены вендора в продукте не зашиты — вендор не выбран (`HANDOFF` §6): их вносит
 * администратор в параметры профиля провайдера, как температуру и лимит токенов. У профиля без
 * цены (и у заглушки) стоимость — 0, как было.
 */

export interface AiPrice {
  /** Цена миллиона входных токенов в минорных единицах валюты (центы, копійки); дробная допустима. */
  priceInPer1M?: number
  /** Цена миллиона выходных токенов в минорных единицах. */
  priceOutPer1M?: number
  /** ISO 4217, `EUR` по умолчанию — как колонка `ai_calls.currency`. */
  currency?: string
}

export const AI_DEFAULT_CURRENCY = 'EUR'

/**
 * Стоимость одного вызова в минорных единицах — **с округлением вверх**: вызов дешёвой модели
 * стоит доли цента, и честное округление записало бы в журнал ноль у платного вызова, а сумма
 * нулей в «Вартості ШІ» — ноль у тысяч вызовов. Переплата отчёта — меньше одной минорной
 * единицы на вызов. Токены неизвестны (драйвер не вернул `usage`) — 0: оценивать нечем.
 */
export function callCostMinor(tokensIn: number | null, tokensOut: number | null, price: AiPrice): number {
  const raw = ((tokensIn ?? 0) * (price.priceInPer1M ?? 0) + (tokensOut ?? 0) * (price.priceOutPer1M ?? 0)) / 1_000_000
  return raw > 0 ? Math.ceil(raw - 1e-9) : 0
}
