import type { ContentType } from '../enums'

/**
 * Бали, бонуси і магазин (docs/21 §3.7, §14.3, §14.9, Г-21.1; docs/15 §14.3 «Нагороди»; docs/02 §2.10).
 * Чисті константи й правила без Vue/Nitro — ними користуються схема налаштувань тенанта
 * (`shared/schemas/settings.ts`), сервер (`server/services/rewards.ts`, `shop.ts`) і екрани.
 *
 * Дві валюти однієї книги (`points_ledger.currency`): **бали** — у рейтинг («Поточний рейтинг»,
 * docs/22 §13.5), лише накопичуються; **бонуси** — у магазин подарунків, накопичуються й
 * витрачаються. Так у еталона: у формі призначення це два окремі поля (docs/15 §14.3).
 */

/** Нагорода за виконання завдання: скільки балів у рейтинг і скільки бонусів у магазин. */
export interface TaskReward { points: number, bonuses: number }

/**
 * Правила нарахування за замовчуванням — «Виконання завдання» (подія журналу еталона, docs/21
 * §14.9) по типу контенту. Значення з параметрів призначення («Бали/Бонуси за виконання
 * завдання», docs/15 §14.3) перекривають правило; тенант змінює правила на екрані «Правила
 * нарахування» (`tenants.settings.gamification.taskRewards`).
 *
 * `[решение]` Числа — не з еталона (у нього суми задаються лише в призначенні, за замовчуванням 0),
 * а з масштабу, який еталон показує даними: курс у журналі — «+5», коротке завдання — «+1»,
 * подарунки коштують 11–30 бонусів, залишки людей — 0–40 (docs/21 §14.3, §14.9). Отже бонусів
 * за курс 5: подарунок — це 3–6 пройдених курсів, а не один і не сотня. Бали рейтингу — удесятеро
 * більші за бонуси: рейтинг лише росте й порівнює людей, дрібна шкала там злипається.
 * Анкета оцінки колег, чек-лист спостерігача й підтвердження оголошення — 0: перше й друге —
 * робота оцінювача, а не навчання; за ознайомлення з обовʼязковим правилом не платять.
 */
export const DEFAULT_TASK_REWARDS: Record<ContentType, TaskReward> = {
  course: { points: 50, bonuses: 5 },
  training_program: { points: 100, bonuses: 10 },
  resource: { points: 10, bonuses: 1 },
  test: { points: 30, bonuses: 3 },
  complex_test: { points: 50, bonuses: 5 },
  workshop: { points: 50, bonuses: 5 },
  poll: { points: 10, bonuses: 1 },
  assessment: { points: 0, bonuses: 0 },
  check_list: { points: 0, bonuses: 0 },
  meetup: { points: 30, bonuses: 3 },
  webinar: { points: 20, bonuses: 2 },
  notice: { points: 0, bonuses: 0 },
}

/** Верхня межа однієї нагороди й однієї ручної операції — та сама, що в параметрах призначення (`quizParamsSchema.points/bonuses`). */
export const MAX_REWARD = 10_000

