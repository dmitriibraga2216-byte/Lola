import type { Scope } from './roles'

/**
 * Двухфакторный вход (docs/24 §3.4 «Двухфакторность для админов», docs/v2/39 П-24.1: «TOTP —
 * включение на уровне тенанта»). Константы общие для сервера и экрана.
 *
 * **Кого касается политика тенанта.** «Для админов» определяется правом, а не кодом роли
 * (дух инварианта 16): человек, у которого среди действующих ролей есть скоуп настроек
 * пространства. Сегодня это `admin` и `owner`, и своя роль тенанта с этим скоупом тоже
 * попадает под политику — ровно потому, что она даёт те же ключи от пространства.
 * Остальные могут подключить второй фактор добровольно; подключённый спрашивается при
 * каждом входе независимо от политики.
 */
export const TWO_FACTOR_ADMIN_SCOPE: Scope = 'settings.tenant'

/** Промежуточная сессия «первый фактор пройден, второго нет»: живёт 10 минут. */
export const TWO_FACTOR_PENDING_MINUTES = 10

/** Новый секрет, показанный на экране подключения, ждёт первого кода 15 минут. */
export const TWO_FACTOR_SETUP_MINUTES = 15

/** Издатель в приложении-аутентификаторе («Lola» над шестью цифрами). */
export const TWO_FACTOR_ISSUER = 'Lola'

/**
 * Состояние промежуточной сессии для экрана входа: `verify` — второй фактор подключён,
 * нужен код; `enroll` — политика требует фактор, а он ещё не подключён: подключить можно
 * прямо на экране входа, не получая полной сессии.
 */
export type TwoFactorStep = 'verify' | 'enroll'
